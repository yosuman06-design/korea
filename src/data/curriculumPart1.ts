export const FINAL_JAMO = ['', 'ㄱ', 'ㄲ', 'ㄴ', 'ㄷ', 'ㄹ', 'ㅁ', 'ㅂ', 'ㅅ', 'ㅆ', 'ㅇ', 'ㅈ', 'ㅊ', 'ㅋ', 'ㅌ', 'ㅍ', 'ㅎ'];
export const FINAL_UNICODE_INDEX = [0, 1, 2, 4, 7, 8, 16, 17, 19, 20, 21, 22, 23, 24, 25, 26, 27];
export const FINAL_ROMAN = ['', 'k', 'k', 'n', 't', 'l', 'm', 'p', 't', 't', 'ng', 't', 't', 'k', 't', 'p', 't'];

export function composeHangul(initialIdx: number, medialIdx: number, finalIdx: number): { syllable: string; roman: string } {
  const realFinal = FINAL_UNICODE_INDEX[finalIdx] ?? 0;
  const code = 0xac00 + initialIdx * 588 + medialIdx * 28 + realFinal;
  const syllable = String.fromCharCode(code);
  const roman = `${INITIAL_ROMAN[initialIdx]}${MEDIAL_ROMAN[medialIdx]}${FINAL_ROMAN[finalIdx]}`;
  return { syllable, roman };
}

